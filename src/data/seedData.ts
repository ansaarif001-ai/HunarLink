export function buildInitialPortfolioItems(
  workers: WorkerProfile[],
  nowMs: number = Date.now()
): PortfolioItem[] {
  const daysAgo = (d: number) => new Date(nowMs - d * 24 * 3600 * 1000).toISOString();
  const items: PortfolioItem[] = [];

  workers.forEach((w, wIdx) => {
    w.workPhotos.forEach((wp, pIdx) => {
      items.push({
        id: `pf_${w.id}_${pIdx + 1}`,
        workerId: w.id,
        categoryId: wp.categoryId || w.categoryId,
        caption: `${wp.title} — ${wp.caption}`,
        photos: [
          {
            id: wp.id,
            title: wp.title,
            palette: wp.palette,
            categoryId: wp.categoryId || w.categoryId,
            dataUrl: wp.dataUrl,
          },
        ],
        createdAt: daysAgo(15 + wIdx * 3 + pIdx * 2),
      });
    });
  });

  return items;
}

